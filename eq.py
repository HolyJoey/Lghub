"""Headset equalizer: a 10-band EQ as a PipeWire filter-chain, in front of the headset.

The engine runs `pipewire -c <generated config>`; that process adds a sink "<headset>
(Equalizer)" whose output goes to the headset. Gain changes are applied live with pw-cli,
without restarting it. The EQ is ours (PipeWire's biquads), not Logitech's.
"""
import json
import os
import subprocess
import time

import pw
import store

EQ_FILE = os.path.join(store.CONFIG_DIR, 'equalizer.json')
CONF_FILE = os.path.join(store.RUN_DIR, 'equalizer.conf')
SINK = 'lghub_eq'
OWN_NODES = (SINK, 'lghub_surround', pw.VIRTUAL_MIC)   # ours, never a target
OUT = 'lghub_eq_out'
BANDS = (32, 64, 125, 250, 500, 1000, 2000, 4000, 8000, 16000)
Q = 1.41                 # about one octave per band
CHECK_EVERY = 5.0        # seconds between full checks (headset plugged in or out)

FLAT = (0,) * len(BANDS)
# G HUB's own 10-band presets (fetched by the installer from Logitech's update server).
PRESETS_FILE = os.path.join(store.DATA_DIR, 'presets', 'equalizer_presets.json')
PRESET_NAMES = {'EQUALIZER_FLAT': 'Flat', 'EQUALIZER_FPS': 'FPS', 'EQUALIZER_MOBA': 'MOBA',
                'EQUALIZER_BASS_BOOST': 'Bass Boost', 'EQUALIZER_CINEMATIC': 'Cinematic',
                'EQUALIZER_COMMUNICATIONS': 'Communications'}


def load_presets(path=PRESETS_FILE):
	"""{name: gains} from G HUB's preset file; just Flat without it."""
	found = {'Flat': FLAT}
	try:
		with open(path) as f:
			data = json.load(f)
	except (OSError, ValueError):
		return found
	for p in data.get('presets', []):
		eq = p.get('equalizer') or {}
		gains = eq.get('advanced')
		if p.get('attribute') == 'EQUALIZER' and eq.get('type') == 'ADVANCED' and len(gains or []) == len(BANDS):
			name = PRESET_NAMES.get(p.get('name'), p.get('name', '').replace('EQUALIZER_', '').title())
			found[name] = tuple(float(g) for g in gains)
	return found


PRESETS = load_presets()
# Sliders reach as far as the presets do (G HUB's go down to -17 dB), and at least 12 dB.
RANGE = float(max([12] + [abs(g) for gains in PRESETS.values() for g in gains]))


def default_settings():
	return {'enabled': False, 'preset': 'Flat', 'gains': list(FLAT),
	        'target': 'auto', 'make_default': True}


def load():
	settings = default_settings()
	try:
		with open(EQ_FILE) as f:
			saved = json.load(f)
	except (OSError, ValueError):
		return settings
	settings.update({k: v for k, v in saved.items() if k in settings})
	gains = [float(g) for g in settings['gains']][:len(BANDS)]
	settings['gains'] = [max(-RANGE, min(RANGE, g)) for g in gains + [0.0] * (len(BANDS) - len(gains))]
	return settings


def save(settings):
	store._write_json(EQ_FILE, settings)


def band_name(i):
	return f'band{i + 1}'


def band_label(i):
	freq = BANDS[i]
	return f'{freq // 1000}k' if freq >= 1000 else str(freq)


def config_text(target, description, gains):
	nodes, links = [], []
	kinds = ['bq_lowshelf'] + ['bq_peaking'] * (len(BANDS) - 2) + ['bq_highshelf']
	for i, (freq, kind) in enumerate(zip(BANDS, kinds)):
		nodes.append(f'{{ type = builtin name = {band_name(i)} label = {kind} '
		             f'control = {{ "Freq" = {freq} "Q" = {Q} "Gain" = {gains[i]:.2f} }} }}')
		if i:
			links.append(f'{{ output = "{band_name(i - 1)}:Out" input = "{band_name(i)}:In" }}')
	return f'''# Generated by Lghub; rewritten on every start.
context.properties = {{ log.level = 0 }}
context.spa-libs = {{
	audio.convert.* = audioconvert/libspa-audioconvert
	support.* = support/libspa-support
}}
context.modules = [
	{{ name = libpipewire-module-rt flags = [ ifexists nofail ] }}
	{{ name = libpipewire-module-protocol-native }}
	{{ name = libpipewire-module-client-node }}
	{{ name = libpipewire-module-adapter }}
	{{ name = libpipewire-module-filter-chain
		args = {{
			node.description = {json.dumps(description)}
			media.name = {json.dumps(description)}
			filter.graph = {{
				nodes = [
					{(chr(10) + chr(9) * 5).join(nodes)}
				]
				links = [
					{(chr(10) + chr(9) * 5).join(links)}
				]
			}}
			audio.channels = 2
			audio.position = [ FL FR ]
			capture.props = {{ node.name = {SINK} media.class = Audio/Sink }}
			playback.props = {{ node.name = {OUT} node.passive = true target.object = {json.dumps(target)}
				stream.dont-remix = true }}
		}}
	}}
]
'''


def sinks(objs=None):
	"""Real outputs: [{'id', 'name', 'description'}], without our own (equalizer, surround)."""
	out = []
	for o in objs if objs is not None else pw.dump():
		p = pw._props(o)
		if o.get('type', '').endswith('Node') and p.get('media.class') == 'Audio/Sink' \
				and p.get(pw.NODE_NAME) not in OWN_NODES:
			out.append({'id': o['id'], 'name': p.get(pw.NODE_NAME, ''),
			            'description': p.get('node.description') or p.get(pw.NODE_NAME, '')})
	return out


def pick_target(wanted, objs=None):
	"""The sink to equalize: the chosen one, else the headset; None when it isn't there."""
	found = sinks(objs)
	for s in found:
		if (wanted not in ('auto', None) and s['name'] == wanted) or (wanted in ('auto', None) and pw.is_blue_voice_headset(s)):
			return s
	return None


def set_gains(gains, objs=None):
	"""Change the running EQ's gains in place."""
	nid = pw.node_id(SINK, objs)
	if nid is None:
		return False
	params = ' '.join(f'"{band_name(i)}:Gain" {g:.2f}' for i, g in enumerate(gains))
	r = subprocess.run(['pw-cli', 'set-param', str(nid), 'Props', f'{{ params = [ {params} ] }}'],
	                   capture_output=True, text=True, timeout=5)
	return r.returncode == 0


class Runner:
	"""Used by the engine: keeps the EQ process in line with equalizer.json."""

	def __init__(self):
		self.proc = None
		self.target = None
		self.gains = None
		self.mtime = None
		self.settings = default_settings()
		self.defaulted = False
		self.last_check = 0.0

	def due(self):
		"""True when equalizer.json changed or a periodic check is due; cheap to call often."""
		try:
			mtime = os.stat(EQ_FILE).st_mtime
		except FileNotFoundError:
			mtime = None
		if mtime != self.mtime:
			self.mtime = mtime
			self.settings = load()
			return True
		return time.monotonic() - self.last_check >= CHECK_EVERY

	def check(self, objs):
		self.last_check = time.monotonic()
		s = self.settings
		target = pick_target(s.get('target'), objs) if s.get('enabled') else None
		if self.proc and self.proc.poll() is not None:
			self.proc = None
		if not target:
			self.stop(objs)
			return
		if not self.proc or target['name'] != self.target:
			self.stop(objs)
			self._start(target, s['gains'])
			return
		if s['gains'] != self.gains and set_gains(s['gains'], objs):
			self.gains = list(s['gains'])
		if s.get('make_default') and not self.defaulted and pw.node_id(SINK, objs) is not None:
			nid = pw.node_id(SINK, objs)
			subprocess.run(['wpctl', 'set-default', str(nid)], capture_output=True)
			self.defaulted = True

	def _start(self, target, gains):
		os.makedirs(store.RUN_DIR, exist_ok=True)
		with open(CONF_FILE, 'w') as f:
			f.write(config_text(target['name'], f"{target['description']} (Equalizer)", gains))
		try:
			self.proc = subprocess.Popen(['pipewire', '-c', CONF_FILE], stdin=subprocess.DEVNULL,
			                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
			                             start_new_session=True)
		except OSError as e:
			print(f'engine: equalizer not started: {e}', flush=True)
			return
		self.target = target['name']
		self.gains = list(gains)
		self.defaulted = False
		print(f"engine: equalizer on {target['name']}", flush=True)

	def stop(self, objs=None):
		if not self.proc:
			return
		if self.defaulted:
			nid = pw.node_id(self.target, objs)
			if nid is not None:  # hand the default back to the headset itself
				subprocess.run(['wpctl', 'set-default', str(nid)], capture_output=True)
		self.proc.terminate()
		try:
			self.proc.wait(timeout=5)
		except subprocess.TimeoutExpired:
			self.proc.kill()
		self.proc = None
		self.target = None
		self.defaulted = False
